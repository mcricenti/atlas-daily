/**
 * Works out borders and areas for every state and country from the map files,
 * and writes src/data/geo/geoFacts.ts.  Run after changing the map or the facts:
 *   npx tsx scripts/build-geo-facts.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoArea } from 'd3-geo'
import { FACTS } from '../src/data/curriculum'
import { buildAtlas, isUsFact, shapeKeyForFact } from '../src/lib/geoData'

const root = new URL('..', import.meta.url).pathname
const read = (p: string) => JSON.parse(readFileSync(root + p, 'utf8'))
const topo = { us: read('public/geo/states-10m.json'), world: read('public/geo/countries-50m.json') }

const SQ_MI_PER_STERADIAN = (3958.8 * 3958.8)
const out: Record<string, { neighbors: string[]; borderNames: string[]; areaSqMi: number }> = {}

for (const kind of ['us', 'world'] as const) {
  const t = topo[kind]
  const atlas = buildAtlas(t, kind)
  const obj = t.objects[kind === 'us' ? 'states' : 'countries']
  const features = (feature(t, obj) as any).features as any[]
  const areaByKey = new Map<string, number>()
  for (const f of features) {
    const key = kind === 'us' ? f.properties.name : atlas.shapes.find((s) => s.name === f.properties.name)?.key
    if (key) areaByKey.set(key, (areaByKey.get(key) ?? 0) + geoArea(f) * SQ_MI_PER_STERADIAN)
  }
  for (const fact of FACTS) {
    if ((kind === 'us') !== isUsFact(fact)) continue
    const key = shapeKeyForFact(fact)
    if (!key || !atlas.byKey.has(key)) continue
    const nKeys = atlas.neighbors.get(key) ?? []
    const neighborFacts = FACTS.filter((f) => {
      const k = shapeKeyForFact(f)
      return k && nKeys.includes(k) && isUsFact(f) === isUsFact(fact)
    }).map((f) => f.id)
    out[fact.id] = {
      neighbors: neighborFacts,
      borderNames: nKeys.map((k) => atlas.byKey.get(k)!.label.replace(/^the /, '')),
      areaSqMi: Math.round(areaByKey.get(key) ?? 0),
    }
  }
}

const body = Object.entries(out)
  .map(([id, v]) => `  '${id}': ${JSON.stringify(v)},`)
  .join('\n')
writeFileSync(
  root + 'src/data/geo/geoFacts.ts',
  `// Generated by scripts/build-geo-facts.ts — do not edit by hand.
/** neighbors: fact ids that share a border; borderNames: every bordering place; areaSqMi: land area. */
export type GeoFacts = { neighbors: string[]; borderNames: string[]; areaSqMi: number }

export const GEO_FACTS: Record<string, GeoFacts> = {
${body}
}
`,
)
console.log('wrote', Object.keys(out).length, 'places')
